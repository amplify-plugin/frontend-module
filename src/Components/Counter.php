<?php

namespace Amplify\Frontend\Components;

use Amplify\Frontend\Abstracts\BaseComponent;
use Closure;
use Illuminate\Contracts\View\View;
use Illuminate\Support\Facades\Validator;

/**
 * @class Counter
 */
class Counter extends BaseComponent
{
    public array $entries = [];

    /**
     * @param string $items
     * @param string $fontColor
     * @param int $desktopItems
     * @param int $tabletItems
     * @param string $counterFontSize
     * @param string $labelFontSize
     */
    public function __construct(string        $items = '[]',
                                public string $fontColor = '#000',
                                public int    $desktopItems = 4,
                                public int    $tabletItems = 2,
                                public string $counterFontSize = '32px',
                                public string $labelFontSize = '16px')
    {
        parent::__construct();

        $this->entries = json_decode($items);

    }

    /**
     * Whether the component should be rendered
     */
    public function shouldRender(): bool
    {
        return !empty($this->entries);
    }

    /**
     * Get the view / contents that represent the component.
     */
    public function render(): View|Closure|string
    {
        return view('widget::counter');
    }

    public function htmlAttributes(): string
    {
        $this->attributes = $this->attributes->style([
            '--items: ' . count($this->entries),
            '--desktop: ' . $this->desktopItems,
            '--tablets: ' . $this->tabletItems,
            '--mobile: ' . 2,
        ]);

        return parent::htmlAttributes(); // TODO: Change the autogenerated stub
    }
}
